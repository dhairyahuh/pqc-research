"""ASTRA-Sec: ION-DTN Contact Plan & Range Schedule Parser and Evaluator."""

import logging
import time
from typing import Dict, List, Optional, Tuple

logger = logging.getLogger("astra_sec.dtn.contact_plan")


class IonContact:
    """Represents an orbital contact window defined in an ION-DTN contact plan."""

    def __init__(
        self,
        from_node: int,
        to_node: int,
        start_time: int,
        stop_time: int,
        xmit_rate_bps: int = 1000000,
    ):
        self.from_node = from_node
        self.to_node = to_node
        self.start_time = start_time
        self.stop_time = stop_time
        self.xmit_rate_bps = xmit_rate_bps

    def is_active(self, current_time: int) -> bool:
        return self.start_time <= current_time <= self.stop_time

    def to_ion_command(self) -> str:
        return f"a contact {self.start_time} {self.stop_time} {self.from_node} {self.to_node} {self.xmit_rate_bps}"


class IonRange:
    """Represents one-way light time (OWLT) distance between nodes in ION-DTN."""

    def __init__(
        self,
        from_node: int,
        to_node: int,
        start_time: int,
        stop_time: int,
        owlt_seconds: int = 1,
    ):
        self.from_node = from_node
        self.to_node = to_node
        self.start_time = start_time
        self.stop_time = stop_time
        self.owlt_seconds = owlt_seconds

    def to_ion_command(self) -> str:
        return f"a range {self.start_time} {self.stop_time} {self.from_node} {self.to_node} {self.owlt_seconds}"


class IonContactPlan:
    """Manages NASA/JPL ION-DTN contact schedules and node reachability."""

    def __init__(self):
        self.contacts: List[IonContact] = []
        self.ranges: List[IonRange] = []

    def add_contact(
        self,
        from_node: int,
        to_node: int,
        start_time: int,
        stop_time: int,
        xmit_rate_bps: int = 1000000,
    ) -> IonContact:
        contact = IonContact(from_node, to_node, start_time, stop_time, xmit_rate_bps)
        self.contacts.append(contact)
        return contact

    def add_range(
        self,
        from_node: int,
        to_node: int,
        start_time: int,
        stop_time: int,
        owlt_seconds: int = 1,
    ) -> IonRange:
        r = IonRange(from_node, to_node, start_time, stop_time, owlt_seconds)
        self.ranges.append(r)
        return r

    def is_contact_open(self, from_node: int, to_node: int, current_time: Optional[int] = None) -> bool:
        """Determines if a directional contact is active at current_time."""
        now = current_time if current_time is not None else int(time.time())
        # Check active contact
        for c in self.contacts:
            if c.from_node == from_node and c.to_node == to_node and c.is_active(now):
                return True
        # If no contacts defined between these nodes, return False
        return False

    def export_ionrc_script(self) -> str:
        """Generates standard ionadmin commands for loading into ION-DTN."""
        lines = [
            "# NASA/JPL ION-DTN Contact Plan Configuration",
            "# Generated by ASTRA-Sec DTN Orchestrator",
            "1",  # Initialize SDR / admin mode
        ]
        for c in self.contacts:
            lines.append(c.to_ion_command())
        for r in self.ranges:
            lines.append(r.to_ion_command())
        lines.append("m horizon +0")
        lines.append("s")  # Start
        return "\n".join(lines) + "\n"
