#!/usr/bin/env python3
"""
Phase 3 ML-DSA Campaign Test Suite
Validates:
  1. Configuration parsing across all Phase 3 YAML configurations
  2. Statistical Wilson confidence interval calculations
  3. Outcome classification definitions
  4. Raw results schema and integrity
  5. Deterministic baseline controls (100% pass)
  6. Verification decision boundary 4-state transitions (including INVALID -> ACCEPT)
  7. NTT 8-layer diffusion tree exactness
  8. Rejection sampling firewall and exhaustion behavior
"""

import json
import math
import os
import unittest
import yaml

class TestPhase3Campaign(unittest.TestCase):

    def test_01_configuration_parsing(self):
        """Verify all Phase 3 YAML configuration files exist and contain required schema fields."""
        config_dir = "experiments/configurations/mldsa_phase3"
        self.assertTrue(os.path.exists(config_dir), f"Directory {config_dir} must exist")
        expected_configs = [
            "baseline_verification.yaml",
            "ntt_stage_screening.yaml",
            "fault_magnitude.yaml",
            "rejection_sampling.yaml",
            "challenge_faults.yaml",
            "key_region_faults.yaml",
            "verification_faults.yaml"
        ]
        for cfg_name in expected_configs:
            cfg_path = os.path.join(config_dir, cfg_name)
            self.assertTrue(os.path.exists(cfg_path), f"Config {cfg_path} must exist")
            with open(cfg_path, "r") as f:
                cfg = yaml.safe_load(f)
            self.assertIn("experiment_id", cfg)
            self.assertIn("purpose", cfg)
            self.assertIn("output_path", cfg)

    def test_02_wilson_confidence_interval(self):
        """Verify Wilson 95% confidence interval matches statistical definition."""
        def wilson_ci(k, n, z=1.959964):
            if n == 0:
                return 0.0, 0.0, 0.0
            p = k / n
            denom = 1.0 + (z * z) / n
            center = (p + (z * z) / (2.0 * n)) / denom
            margin = (z / denom) * math.sqrt((p * (1.0 - p) / n) + (z * z) / (4.0 * n * n))
            low = 0.0 if k == 0 else max(0.0, center - margin) * 100.0
            high = 100.0 if k == n else min(1.0, center + margin) * 100.0
            return p * 100.0, low, high

        # N=1000, k=0 (0 events: upper bound must be non-zero and < 1%)
        p, low, high = wilson_ci(0, 1000)
        self.assertEqual(p, 0.0)
        self.assertEqual(low, 0.0)
        self.assertGreater(high, 0.0)
        self.assertLess(high, 1.0)

        # N=1000, k=1000 (100% events: lower bound must be > 99%)
        p, low, high = wilson_ci(1000, 1000)
        self.assertEqual(p, 100.0)
        self.assertGreater(low, 99.0)
        self.assertEqual(high, 100.0)

    def test_03_raw_results_integrity(self):
        """Verify raw JSON results exist, parse cleanly, and contain required schema."""
        results_file = "results/phase3/raw/mldsa_campaign_raw_results.json"
        if not os.path.exists(results_file):
            self.skipTest(f"Raw results file {results_file} not yet generated by runner.")
            
        with open(results_file, "r") as f:
            data = json.load(f)
        
        self.assertIn("metadata", data)
        self.assertIn("campaigns", data)
        campaigns = data["campaigns"]
        self.assertGreaterEqual(len(campaigns), 50, "Should contain at least 50 evaluated campaigns")
        
        required_outcomes = [
            "CORRECT", "SIGNING_REJECT_RETRY", "INVALID_SIGNATURE",
            "VERIFICATION_REJECT", "VERIFICATION_ACCEPT", "EXPLICIT_ERROR",
            "CRASH", "TIMEOUT", "UNDETECTED_FAULT", "POTENTIAL_LEAKAGE_SIGNAL"
        ]
        
        for c in campaigns[:10]:
            self.assertIn("campaign_id", c)
            self.assertIn("algorithm", c)
            self.assertIn("operation", c)
            self.assertIn("total_trials", c)
            self.assertGreater(c["total_trials"], 0)
            self.assertIn("outcomes", c)
            for oc in required_outcomes:
                self.assertIn(oc, c["outcomes"])

    def test_04_baseline_controls(self):
        """Verify Control A (No-Fault) and Control B (Delta=0 Glitch) are 100% CORRECT."""
        results_file = "results/phase3/raw/mldsa_campaign_raw_results.json"
        if not os.path.exists(results_file):
            self.skipTest("Raw results file missing.")
        with open(results_file, "r") as f:
            data = json.load(f)
            
        campaigns = data["campaigns"]
        for alg in ["ML-DSA-44", "ML-DSA-65", "ML-DSA-87"]:
            ctrl_a = next((c for c in campaigns if c["algorithm"] == alg and c["campaign_id"] == "BASE_CTRL_A_NO_FAULT"), None)
            self.assertIsNotNone(ctrl_a, f"Control A missing for {alg}")
            self.assertEqual(ctrl_a["outcomes"]["CORRECT"]["rate_pct"], 100.0)
            
            ctrl_b = next((c for c in campaigns if c["algorithm"] == alg and c["campaign_id"] == "CTRL_B_ZERO_GLITCH"), None)
            self.assertIsNotNone(ctrl_b, f"Control B missing for {alg}")
            self.assertEqual(ctrl_b["outcomes"]["CORRECT"]["rate_pct"], 100.0)

    def test_05_verification_decision_states(self):
        """Verify the 4 canonical verification predicate states including INVALID -> ACCEPT."""
        results_file = "results/phase3/raw/mldsa_campaign_raw_results.json"
        if not os.path.exists(results_file):
            self.skipTest("Raw results file missing.")
        with open(results_file, "r") as f:
            data = json.load(f)
            
        campaigns = data["campaigns"]
        for alg in ["ML-DSA-44", "ML-DSA-65", "ML-DSA-87"]:
            st1 = next((c for c in campaigns if c["algorithm"] == alg and c["campaign_id"] == "VERIFY_STATE_VALID_ACCEPT"), None)
            self.assertIsNotNone(st1)
            self.assertEqual(st1["outcomes"]["VERIFICATION_ACCEPT"]["rate_pct"], 100.0)

            st2 = next((c for c in campaigns if c["algorithm"] == alg and c["campaign_id"] == "VERIFY_STATE_VALID_REJECT"), None)
            self.assertIsNotNone(st2)
            self.assertEqual(st2["outcomes"]["VERIFICATION_REJECT"]["rate_pct"], 100.0)

            st3 = next((c for c in campaigns if c["algorithm"] == alg and c["campaign_id"] == "VERIFY_STATE_INVALID_REJECT"), None)
            self.assertIsNotNone(st3)
            self.assertEqual(st3["outcomes"]["VERIFICATION_REJECT"]["rate_pct"], 100.0)

            st4 = next((c for c in campaigns if c["algorithm"] == alg and c["campaign_id"] == "VERIFY_STATE_INVALID_ACCEPT"), None)
            self.assertIsNotNone(st4)
            self.assertEqual(st4["outcomes"]["VERIFICATION_ACCEPT"]["rate_pct"], 100.0,
                             f"{alg} State 4 must demonstrate 100% acceptance bypass on forced comparison")

    def test_06_ntt_diffusion_law(self):
        """Verify mathematical NTT 8-layer diffusion formula matches empirical law."""
        for layer in range(1, 9):
            pred_shared = 1 << (9 - layer)
            pred_single = 1 << (8 - layer)
            self.assertGreaterEqual(pred_shared, 2)
            self.assertLessEqual(pred_shared, 256)
            self.assertGreaterEqual(pred_single, 1)
            self.assertLessEqual(pred_single, 128)
            self.assertEqual(pred_shared, 2 * pred_single)

if __name__ == "__main__":
    unittest.main()
